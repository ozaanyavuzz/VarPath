def normalize_residue_codes(values: pd.Series | list | np.ndarray) -> np.ndarray:
    """Upper-case, strip and replace missing codes with ``'X'``."""
    s = pd.Series(values, dtype="object")
    s = s.where(s.notna(), "X")
    return s.astype(str).str.strip().str.upper().to_numpy(dtype=object)


def aa_features(aa1: str, aa2: str) -> np.ndarray:
    zero = np.zeros(8)
    p1 = np.asarray(AA_PROPS.get(aa1, zero), dtype=float)
    p2 = np.asarray(AA_PROPS.get(aa2, zero), dtype=float)
    return np.concatenate(
        [p1, p2, p2 - p1, [float(BLOSUM62.get((aa1, aa2), 0)), float(GRANTHAM.get((aa1, aa2), 0))]]
    )


def grantham_distance(aa1: str, aa2: str) -> float:
    return float(GRANTHAM.get((aa1, aa2), 0))


def pairwise_matrix(aa1: np.ndarray, aa2: np.ndarray, fn) -> np.ndarray:
    """Evaluate a row-local pair function once per distinct substitution."""
    cache: dict[tuple[str, str], np.ndarray] = {}
    rows = []
    for a, b in zip(aa1, aa2):
        key = (a, b)
        if key not in cache:
            cache[key] = fn(a, b)
        rows.append(cache[key])
    if not rows:
        return np.zeros((0, len(fn("A", "A"))))
    return np.vstack(rows)
